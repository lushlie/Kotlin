fun main() {

    //arithmetic operators(simple calculations)
    var num1 = 10
    var num2 = 5

    println(num1 + num2)
    println(num1 - num2)
    println(num1 * num2)  //multiply
    println(num1 / num2)  //divide
    println(num1 % num2)  //modules(rem after div)


    //comparison operators (compare)
    var x = 80
    var y = 34

    println(x > y)
    println(x < y)
    println(x >= y)
    println(x <= y)
    println(x == y)    //equal to
    println(x != y)    //not equal to


    //assignment operators(no. to variable)
    var number = 100
    println(number)

    number += 2  //(kinda like bodmas but = first)
    println(number)


    //logical operators (&& (add) || (or) ! (not))
    //&& - all conditions to be true
    //|| - atleast one to be true
    //! - atleast one to be false

    println(100 == 50 && 100 > 30) //&&
    println(100 == 50 || 100 > 30) //||
    println(!(100 == 50 || 100 > 30))  //!







}