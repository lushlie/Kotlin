fun main() {

    var course = "SOFTWARE DEVELOPMENT"
    var school = "eMobilis"

    println(course[0])   //index position

    //size of string
    println(course.length)
    println(school.length)

    //string concatenation (join)
    println(school + course)

    //space
    println(school + " " +  course)

    //string interpolation
    println("I study at $school. I'm currently studying $course")


}